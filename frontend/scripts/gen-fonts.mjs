const root = (p) => new URL(`../${p}`, import.meta.url)
const fp = (pkg, file) => `node_modules/@fontsource/${pkg}/${file}`

// UI font: plain fontsource imports, loaded with the main stylesheet.
const uiLines = ['/* Generated by scripts/gen-fonts.mjs. Faces are fetched only when text uses them. */']
for (const w of [400, 600, 700]) {
  for (const s of ['latin', 'latin-ext', 'cyrillic'])
    uiLines.push(`@import '@fontsource/inter/${s}-${w}.css';`)
}
writeFileSync(root('src/styles/fonts.css'), `${uiLines.join('\n')}\n`)

const css = [
  '/* Generated by scripts/gen-fonts.mjs. Imported lazily by lib/ticket; only woff2 files are referenced. */',
]
const entries = []
const skipped = []
for (const [family, pkg, category] of CATALOG) {
  const weights = [400, 700].filter((w) => existsSync(root(fp(pkg, `cyrillic-${w}.css`))))
  if (weights.length === 0 || !existsSync(root(fp(pkg, `latin-${weights[0]}.css`)))) {
    skipped.push(family)
    continue
  }
  for (const w of weights) {
    for (const subset of ['latin', 'cyrillic']) {
      const file = `${pkg}-${subset}-${w}-normal.woff2`
      if (!existsSync(root(fp(pkg, `files/${file}`)))) throw new Error(`missing ${pkg}/files/${file}`)
      css.push(
        `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${w};` +
          `src:url(../../node_modules/@fontsource/${pkg}/files/${file}) format('woff2');unicode-range:${RANGES[subset]}}`,
      )
    }
  }
  entries.push({ family, category, bold: weights.includes(700) })
}
writeFileSync(root('src/styles/ticketFonts.css'), `${css.join('\n')}\n`)

const ts = [
  '// Generated by scripts/gen-fonts.mjs; do not edit.',
  "export type FontCategory = 'sans' | 'serif' | 'mono' | 'display' | 'script'",
  '',
  'export interface CatalogFont {',
  '  family: string',
  '  category: FontCategory',
  '  /** Whether a real bold face is bundled (otherwise the browser synthesises it). */',
  '  bold: boolean',
  '}',
  '',
  'export const FONT_CATALOG: readonly CatalogFont[] = [',
  ...entries.map((e) => `  { family: '${e.family}', category: '${e.category}', bold: ${e.bold} },`),
  ']',
  '',
]
writeFileSync(root('src/lib/ticket/catalog.gen.ts'), ts.join('\n'))
