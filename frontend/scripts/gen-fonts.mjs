// Regenerates src/styles/fonts.css. Only latin, latin-ext (Uzbek oʻ gʻ) and cyrillic subsets are imported.
import { writeFileSync } from 'node:fs'

const subsets = ['latin', 'latin-ext', 'cyrillic']
const ui = [{ family: 'inter', weights: [400, 600, 700] }]
const ticket = ['montserrat', 'roboto', 'open-sans', 'pt-sans', 'oswald', 'playfair-display', 'arimo'].map(
  (family) => ({ family, weights: [400, 700] }),
)

const lines = ['/* Generated by scripts/gen-fonts.mjs. Faces are fetched only when text uses them. */']
for (const { family, weights } of [...ui, ...ticket]) {
  for (const w of weights) {
    for (const s of subsets) lines.push(`@import '@fontsource/${family}/${s}-${w}.css';`)
  }
}
writeFileSync(new URL('../src/styles/fonts.css', import.meta.url), `${lines.join('\n')}\n`)
