// Regenerates src/styles/fonts.css (UI font), src/styles/ticketFonts.css (lazy ticket fonts, woff2 only)
// and src/lib/ticket/catalog.gen.ts (picker metadata). Keep the names in sync with
// backend/internal/domain/project.go (allowedFonts). Every family is SIL OFL 1.1 except Roboto Slab (Apache 2.0).
import { existsSync, writeFileSync } from 'node:fs'

// Standard Google Fonts subset ranges. U+02BB/U+02BC (the Uzbek letters in oʻ and gʻ) live in "latin".
const RANGES = {
  latin:
    'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  cyrillic: 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
}

